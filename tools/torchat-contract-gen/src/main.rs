    let tor_phases = string_list(manifest.get("torPhases"))?;
    let runtime_event_names = string_list(manifest.get("events"))?;
    let connection_states = string_list(manifest.get("connectionStates"))?;
    let transport_phases = string_list(manifest.get("transportPhases"))?;
    let message_states = string_list(manifest.get("messageStates"))?;
    let conversation_states = string_list(manifest.get("conversationStates"))?;
    let invite_states = string_list(manifest.get("inviteStates"))?;
    let pairing_actions = string_list(manifest.get("pairingAvailableActions"))?;
    let message_transport = string_list(manifest.get("messageTransportOutcomes"))?;
    let contact_transport_policies = string_list(manifest.get("contactTransportPolicies"))?;
    let pairing_peer = string_list(manifest.get("pairingPeerOutcomes"))?;
    let peer_endpoint_statuses = string_list(manifest.get("peerEndpointStatuses"))?;
    let peer_connection_statuses = string_list(manifest.get("peerConnectionStatuses"))?;
    let platform_action_types = string_list(manifest.get("platformActionTypes"))?;

    let android_output = repo_root
        .join("apps/mobile/flutter/android/app/src/main/kotlin/org/torchat/generated/EngineContract.kt");
    let dart_contract_output =
        repo_root.join("apps/mobile/flutter/lib/core/runtime/generated/runtime_contract.g.dart");
    let dart_models_output =
        repo_root.join("apps/mobile/flutter/lib/core/models/generated/runtime_models.g.dart");

    write_file(
        &android_output,
        &render_kotlin_contract(
            &method_names,
            &command_types,
            &engine_event_types,
            &response_statuses,
            &response_payload_types,
            &platform_fact_types,
            &tor_phases,
            &runtime_event_names,
            &connection_states,
            &transport_phases,
            &message_states,
            &conversation_states,
            &invite_states,
            &pairing_actions,
            &message_transport,
            &contact_transport_policies,
            &pairing_peer,
            &peer_endpoint_statuses,
            &peer_connection_statuses,
            &platform_action_types,
        ),
    )?;
    write_file(
        &dart_contract_output,
        &render_dart_contract(
            &method_names,
            &command_types,
            &engine_event_types,
            &response_statuses,
            &response_payload_types,
            &platform_fact_types,
            &tor_phases,
            &runtime_event_names,
            &connection_states,
            &transport_phases,
            &message_states,
            &conversation_states,
            &invite_states,
            &pairing_actions,
            &message_transport,
            &contact_transport_policies,
            &pairing_peer,
            &peer_endpoint_statuses,
            &peer_connection_statuses,
            &platform_action_types,
        ),
    )?;
