    out.push('\n');
    render_dart_values(&mut out, "response_payload_", response_payload_types);
    out.push('\n');
    render_dart_values(&mut out, "fact_", platform_fact_types);
    out.push('\n');
    render_dart_values(&mut out, "tor_phase_", tor_phases);
    out.push('\n');
    render_dart_values(&mut out, "", runtime_events);
    out.push('\n');
    render_dart_values(&mut out, "connection_state_", connection_states);
    out.push('\n');
    render_dart_values(&mut out, "transport_phase_", transport_phases);
