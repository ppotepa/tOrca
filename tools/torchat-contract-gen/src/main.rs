fn unique_strings(values: &[String]) -> Vec<&str> {
    let mut seen = BTreeSet::new();
    let mut result = Vec::new();
    for value in values {
        if seen.insert(value.as_str()) {
            result.push(value.as_str());
        }
    }
    result
}

fn screaming_snake(value: &str) -> String {
    if value
        .chars()
        .all(|ch| ch.is_ascii_uppercase() || ch.is_ascii_digit() || ch == '_')
    {
        return value.to_owned();
    }
    let mut out = String::new();
    let mut last_was_separator = true;
    for ch in value.chars() {
        if ch.is_ascii_alphanumeric() {
            if ch.is_ascii_uppercase() && !last_was_separator && !out.ends_with('_') {
                out.push('_');
            }
            out.push(ch.to_ascii_uppercase());
            last_was_separator = false;
        } else {
            if !out.ends_with('_') {
                out.push('_');
            }
            last_was_separator = true;
        }
    }
    out.trim_matches('_').to_owned()
}

fn upper_camel_identifier(value: &str) -> String {
    let lower = lower_camel_identifier(value);
    let mut chars = lower.chars();
    match chars.next() {
        Some(first) => first.to_ascii_uppercase().to_string() + chars.as_str(),
        None => String::new(),
    }
}

fn lower_camel_identifier(value: &str) -> String {
    if value.contains('_') || value.contains('-') {
        let mut words = value
            .split(['_', '-'])
            .filter(|word| !word.is_empty())
            .map(str::to_ascii_lowercase);
        let Some(first) = words.next() else {
            return String::new();
        };
        let mut out = first;
        for word in words {
            let mut chars = word.chars();
            if let Some(first) = chars.next() {
                out.push(first.to_ascii_uppercase());
                out.push_str(chars.as_str());
            }
        }
        return out;
    }

    if value
        .chars()
        .all(|ch| ch.is_ascii_uppercase() || ch.is_ascii_digit())
    {
        return value.to_ascii_lowercase();
    }

    let mut chars = value.chars();
    match chars.next() {
        Some(first) => first.to_ascii_lowercase().to_string() + chars.as_str(),
        None => String::new(),
    }
}
